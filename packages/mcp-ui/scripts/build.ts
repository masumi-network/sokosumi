/**
 * Builds every view in src/views/<id>/ into one self-contained HTML file
 * (inline JS and CSS, nothing fetched at render time), then writes the
 * registry Core imports: dist/index.js and dist/index.d.ts.
 *
 *   node scripts/build.ts
 */
import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import tailwindcss from "@tailwindcss/vite";
import { build } from "vite";

const PACKAGE_DIR = fileURLToPath(new URL("..", import.meta.url));
const VIEWS_DIR = join(PACKAGE_DIR, "src", "views");

/** The view ids: each directory in src/views with an index.html. */
export function viewIds(): string[] {
  return readdirSync(VIEWS_DIR, { withFileTypes: true })
    .filter(
      (entry) =>
        entry.isDirectory() &&
        existsSync(join(VIEWS_DIR, entry.name, "index.html")),
    )
    .map((entry) => entry.name)
    .sort();
}

interface BuiltView {
  id: string;
  uri: string;
  html: string;
}

/** Vite's module script and stylesheet tags in a built index.html. */
const ASSET_TAG =
  /<script\b[^>]*\bsrc="([^"]+)"[^>]*><\/script>|<link\b[^>]*\brel="stylesheet"[^>]*\bhref="([^"]+)"[^>]*>/g;

/** Swaps Vite's script and stylesheet tags for the files' contents, in one pass. */
export function inlineAssets(
  html: string,
  assets: Record<string, string>,
): string {
  const leftover = html
    .replace(ASSET_TAG, "")
    .match(/\s(?:src|href)="([^"]+)"/);
  if (leftover) throw new Error(`Cannot inline ${leftover[1]}`);

  const take = (path: string) => {
    const content = assets[path];
    if (content === undefined) throw new Error(`No built asset ${path}`);
    return content;
  };
  return html.replace(ASSET_TAG, (_tag, src?: string, href?: string) => {
    if (src) {
      const js = take(src).replace(/<\/script/gi, "<\\/script");
      // `<!--` can put the HTML parser in a state where `</script>` no longer ends the script.
      if (js.includes("<!--")) throw new Error(`${src} contains "<!--"`);
      return `<script type="module">${js}</script>`;
    }
    const css = take(href ?? "");
    if (/<\/style/i.test(css)) throw new Error(`${href} closes <style>`);
    return `<style>${css}</style>`;
  });
}

async function buildView(id: string): Promise<string> {
  const result = await build({
    configFile: false,
    root: join(VIEWS_DIR, id),
    mode: "production",
    // Vitest sets NODE_ENV=test, which would bundle React's development build.
    define: { "process.env.NODE_ENV": JSON.stringify("production") },
    logLevel: "warn",
    plugins: [tailwindcss()],
    build: {
      write: false,
      modulePreload: false,
      cssCodeSplit: false,
      assetsInlineLimit: Number.MAX_SAFE_INTEGER,
      reportCompressedSize: false,
      rollupOptions: {
        // lucide-react marks its modules "use client"; views have no server.
        onwarn(warning, warn) {
          if (warning.code !== "MODULE_LEVEL_DIRECTIVE") warn(warning);
        },
      },
    },
  });
  const outputs = Array.isArray(result) ? result : [result];
  const assets: Record<string, string> = {};
  let html: string | undefined;
  for (const output of outputs) {
    if (!("output" in output)) throw new Error("Unexpected watch build");
    for (const file of output.output) {
      const content = file.type === "chunk" ? file.code : String(file.source);
      if (file.fileName === "index.html") html = content;
      else assets[`/${file.fileName}`] = content;
    }
  }
  if (html === undefined) throw new Error(`View ${id} built no index.html`);
  return inlineAssets(html, assets);
}

function registry(views: BuiltView[]): { js: string; dts: string } {
  const header = "// Generated by scripts/build.ts. Do not edit.\n";
  const entries = Object.fromEntries(
    views.map(({ id, uri, html }) => [id, { uri, html }]),
  );
  const ids = views.map(({ id }) => JSON.stringify(id)).join(" | ");
  return {
    js: `${header}export const MCP_UI = Object.freeze(${JSON.stringify(entries)});\n`,
    dts: [
      header,
      `export type UiId = ${ids || "never"};`,
      "export interface McpUiView {",
      "  /** `ui://sokosumi/<id>.<hash8>.html`, hashed from `html`. */",
      "  readonly uri: string;",
      "  /** The view as one self-contained HTML document. */",
      "  readonly html: string;",
      "}",
      "export declare const MCP_UI: Readonly<Record<UiId, McpUiView>>;",
      "",
    ].join("\n"),
  };
}

export async function buildViews(
  outDir = join(PACKAGE_DIR, "dist"),
): Promise<void> {
  const views: BuiltView[] = [];
  for (const id of viewIds()) {
    const html = await buildView(id);
    const hash = createHash("sha256").update(html).digest("hex").slice(0, 8);
    views.push({ id, html, uri: `ui://sokosumi/${id}.${hash}.html` });
  }

  rmSync(join(outDir, "views"), { recursive: true, force: true });
  mkdirSync(join(outDir, "views"), { recursive: true });
  for (const { id, html } of views) {
    writeFileSync(join(outDir, "views", `${id}.html`), html);
  }
  const { js, dts } = registry(views);
  writeFileSync(join(outDir, "index.js"), js);
  writeFileSync(join(outDir, "index.d.ts"), dts);
}

if (import.meta.main) await buildViews();
