// Writes PostgreSQL's unaccent.rules into the Contacts search, so the browser
// folds a place exactly as Core's `unaccent()` does.
//
//   node apps/web/scripts/generate-unaccent-rules.mjs <path/to/unaccent.rules>
//
// The file ships with PostgreSQL (share/tsearch_data/unaccent.rules) and in
// @electric-sql/pglite's dist/unaccent.tar.gz.
import { readFileSync, writeFileSync } from "node:fs";

const source = process.argv[2];
if (!source) throw new Error("Pass the path to unaccent.rules");
const rules = readFileSync(source, "utf8")
  .split("\n")
  .filter(Boolean)
  .map((line) => line.split("\t"))
  .map(([from, to = ""]) => {
    if ([...from].length !== 1) throw new Error(`Not one character: ${from}`);
    // A quoted replacement keeps its spaces; "" inside it is one quote.
    const quoted = to.length > 1 && to.startsWith('"') && to.endsWith('"');
    return `${from}\t${quoted ? to.slice(1, -1).replaceAll('""', '"') : to}`;
  })
  .join("\n");
const literal = JSON.stringify(rules).replace(
  /[^\x20-\x7e]/g,
  (char) => `\\u${char.charCodeAt(0).toString(16).padStart(4, "0")}`,
);
writeFileSync(
  new URL("../src/app/(app)/contacts/unaccent-rules.ts", import.meta.url),
  `// This file is auto-generated by scripts/generate-unaccent-rules.mjs from
// PostgreSQL's unaccent.rules. Do not edit it by hand.

/** Each character unaccent() replaces, tab, what it becomes (empty: dropped). */
export const UNACCENT_RULES =
  ${literal};
`,
);
