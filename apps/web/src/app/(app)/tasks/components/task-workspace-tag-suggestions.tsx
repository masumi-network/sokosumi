"use client";

import { Plus, Sparkles, X } from "lucide-react";
import { useTranslations } from "next-intl";
import type { TaskWorkspaceTag } from "@/app/tasks/types/task-board";
import { Button } from "@/components/ui/button";
import { TaskTagDot } from "./task-tag-colors";

export function WorkspaceTagSuggestions({
  suggestions,
  disabled,
  onAdd,
  onDismiss,
}: {
  suggestions: TaskWorkspaceTag[];
  disabled?: boolean;
  onAdd: (tag: TaskWorkspaceTag) => void;
  onDismiss?: (tag: TaskWorkspaceTag) => void;
}) {
  const t = useTranslations("App.Tasks.Tags");
  if (!suggestions.length) return null;
  return (
    <div className="space-y-1.5">
      <p className="text-muted-foreground flex items-center gap-1 text-xs">
        <Sparkles aria-hidden className="size-3" />
        {t("autoGeneratedTitle")}
      </p>
      <div className="flex flex-wrap gap-1">
        {suggestions.map((tag) => (
          <div key={tag.id} className="flex items-center gap-0.5">
            <Button
              type="button"
              size="sm"
              variant="outline"
              disabled={disabled}
              onClick={() => onAdd(tag)}
              aria-label={t("acceptSuggestion", { name: tag.displayName })}
              className="h-7 gap-1 px-2 text-xs"
            >
              <TaskTagDot {...tag} />
              <span className="truncate">{tag.displayName}</span>
              <Plus aria-hidden className="size-3" />
            </Button>
            {onDismiss && (
              <Button
                type="button"
                size="icon"
                variant="ghost"
                disabled={disabled}
                onClick={() => onDismiss(tag)}
                className="size-10 md:size-8"
                aria-label={t("dismissSuggestion", { name: tag.displayName })}
              >
                <X aria-hidden className="size-3" />
              </Button>
            )}
          </div>
        ))}
      </div>
    </div>
  );
}
